// Builds the MCP App view into one HTML string the worker serves as ui://metabrand/preview.html.
// Run: npm run build:mcp (also part of npm run build).
import { build } from 'vite';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../node_modules/.mcp-app');
mkdirSync(out, { recursive: true });
await build({
  configFile: false,
  logLevel: 'warn',
  build: {
    outDir: out,
    emptyOutDir: true,
    minify: true,
    lib: { entry: resolve(here, 'main.ts'), formats: ['iife'], name: 'MetabrandPreview', fileName: () => 'app.js' },
  },
});
const js = readFileSync(resolve(out, 'app.js'), 'utf8');
const css = readFileSync(resolve(here, 'style.css'), 'utf8');
const html = `<!doctype html><html lang="en" data-theme="light"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Brand preview</title><style>${css}</style></head><body>
<header><span id="title">Metabrand OS</span><button id="open">Open in Metabrand OS ↗</button></header>
<main id="grid" class="grid"><div class="wait">Waiting for the result…</div></main>
<script>${js.replace(/<\/script/gi, '<\\/script')}</script></body></html>`;
writeFileSync(resolve(here, '../functions/_lib/mcp-app.generated.ts'), `// generated by mcp-app/build.mjs, do not edit\nexport const MCP_APP_HTML = ${JSON.stringify(html)};\n`);
console.log(`mcp app: ${(html.length / 1024).toFixed(0)} KB`);
